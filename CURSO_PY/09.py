
# append()   -> Adiciona um elemento ao final da lista.
# clear()    -> Remove todos os elementos da lista.
# copy()     -> Cria uma cópia da lista.
# count()    -> Conta quantas vezes um elemento aparece na lista.
# extend()   -> Adiciona vários elementos de outra lista ao final.
# index()    -> Retorna a posição (índice) de um elemento.
# insert()   -> Adiciona um elemento em uma posição específica.
# pop()      -> Remove e retorna um elemento pelo índice (último, se omitido).
# remove()   -> Remove a primeira ocorrência de um elemento pelo valor.
# reverse()  -> Inverte a ordem dos elementos da lista.
# sort()     -> Organiza os elementos em ordem crescente (ou alfabética).
